"""BEAN evolutionary brute-force strategy laboratory.

A reproducible, credential-free engineering experiment. Candidates mutate and
compete ONLY on training data. The untouched chronological holdout is evaluated
once, after the final champion is selected. No code generated by an LLM is run,
no Coinbase orders are placed, and profits are never guaranteed.
"""
from __future__ import annotations

import argparse
import json
import math
import random
from pathlib import Path

MODES = ("cash", "momentum", "reversal", "dual_trend", "dip_rebound",
         "breakout", "volatility", "regime_rotation")
CHOICES = {
    "mode": MODES,
    "fast": (3, 6, 12, 24, 48, 72),
    "slow": (24, 48, 72, 96, 144),
    "threshold": (0.0, 0.002, 0.005, 0.01, 0.02, 0.035),
    "rebalance": (3, 6, 12, 24, 48),
    "max_positions": (1, 2, 3),
    "allocation": (0.35, 0.6, 0.85, 1.0),
    "stop_loss": (0.0, 0.04, 0.08, 0.15),
    "take_profit": (0.0, 0.08, 0.16, 0.32),
}
COST = 0.006  # Conservative research stress assumption per side, NOT an account fee quote.
MIN_NOTIONAL = 1.0  # Research floor only: exchange-specific real order minimums differ.
WARMUP = 150  # Equal simulated start time for all candidate configurations.
FIELDS = tuple(CHOICES)


def normalize(genome):
    out = {field: genome[field] for field in FIELDS}
    out["slow"] = max(out["slow"], out["fast"] + 1)
    return out


def key(genome):
    return tuple(genome[field] for field in FIELDS)


def random_genome(rng):
    return normalize({name: rng.choice(choices) for name, choices in CHOICES.items()})


def mutate(parent, rng):
    out = dict(parent)
    for field in rng.sample(FIELDS, k=rng.choice((1, 1, 2, 3))):
        out[field] = rng.choice(CHOICES[field])
    return normalize(out)


def crossover(left, right, rng):
    return normalize({field: rng.choice((left[field], right[field])) for field in FIELDS})


def _prices(bars, pair, start, stop):
    return [bars[j]["prices"][pair]["close"] for j in range(start, stop)]


def signals(bars, i, pairs, g):
    """Causal signal: consume only closes strictly before execution bar i."""
    if g["mode"] == "cash":
        return []
    previous = bars[i - 1]["prices"]
    fast_at = bars[i - g["fast"] - 1]["prices"]
    slow_at = bars[i - g["slow"] - 1]["prices"]
    btc = "BTC-USD" if "BTC-USD" in pairs else pairs[0]
    btc_trend = previous[btc]["close"] / slow_at[btc]["close"] - 1.0
    scores = {}
    for pair in pairs:
        current = previous[pair]["close"]
        fast = current / fast_at[pair]["close"] - 1.0
        slow = current / slow_at[pair]["close"] - 1.0
        mode = g["mode"]
        score = None
        if mode == "momentum" and fast > g["threshold"]:
            score = fast
        elif mode == "reversal" and fast < -g["threshold"]:
            score = -fast
        elif mode == "dual_trend" and fast > g["threshold"] and slow > 0:
            score = 0.6 * fast + 0.4 * slow
        elif mode == "dip_rebound" and slow > 0 and fast < -g["threshold"]:
            score = -fast
        elif mode == "breakout" and fast > g["threshold"]:
            historic = _prices(bars, pair, i - g["slow"] - 1, i - 1)
            if historic and current >= max(historic):
                score = fast
        elif mode == "volatility" and fast > g["threshold"]:
            historic = _prices(bars, pair, i - g["fast"] - 1, i)
            changes = [(b / a - 1.0) for a, b in zip(historic, historic[1:])]
            volatility = math.sqrt(sum(x*x for x in changes) / max(1, len(changes)))
            if volatility > 0:
                score = fast / volatility
        elif mode == "regime_rotation" and btc_trend > 0 and fast > g["threshold"]:
            score = fast + 0.3 * slow
        if score is not None and math.isfinite(score):
            scores[pair] = score
    return sorted(scores, key=lambda p: (-scores[p], p))[:g["max_positions"]]


def simulate(bars, genome, pairs, starting=25.0):
    """Simple fee-stressed next-open portfolio execution, no intrabar clairvoyance."""
    if len(bars) <= WARMUP + 8:
        raise ValueError("Insufficient training data for equal-warmup evaluation")
    g = normalize(genome)
    cash = float(starting)
    held = {}  # product -> {units, entry}
    peak = float(starting)
    drawdown = 0.0
    trades = 0
    samples = 0
    for i in range(WARMUP, len(bars)):
        today = bars[i]["prices"]
        prev = bars[i-1]["prices"]
        # Price crosses are checked on LAST closed bar; any liquidation is at
        # today's open. No current high/low, no current close in trade decisions.
        stops = set()
        for pair, entry in held.items():
            change = prev[pair]["close"] / entry["entry"] - 1.0
            if ((g["stop_loss"] > 0 and change <= -g["stop_loss"])
                    or (g["take_profit"] > 0 and change >= g["take_profit"])):
                stops.add(pair)
        if (i - WARMUP) % g["rebalance"] == 0:
            choices = signals(bars, i, pairs, g)
            target = set(choices) - stops
        else:
            target = set(held) - stops
        for pair in tuple(held):
            if pair not in target:
                units = held.pop(pair)["units"]
                cash += units * today[pair]["open"] * (1.0 - COST)
                trades += 1
        nav_open = cash + sum(x["units"] * today[p]["open"] for p, x in held.items())
        if (i - WARMUP) % g["rebalance"] == 0:
            new = sorted(target - set(held))
            target_notional = nav_open * g["allocation"] / g["max_positions"]
            for pair in new:
                spend = min(cash, target_notional)
                if spend < MIN_NOTIONAL:
                    continue
                qty = spend * (1.0 - COST) / today[pair]["open"]
                cash -= spend
                held[pair] = {"units": qty, "entry": today[pair]["open"]}
                trades += 1
        # Include hypothetical liquidation cost in marked portfolio value.
        nav = cash + sum(
            entry["units"] * today[pair]["close"] * (1.0 - COST)
            for pair, entry in held.items()
        )
        peak = max(peak, nav)
        drawdown = max(drawdown, 1.0 - nav / peak)
        samples += 1
    final = cash + sum(
        entry["units"] * bars[-1]["prices"][pair]["close"] * (1.0 - COST)
        for pair, entry in held.items()
    )
    return {"final": round(final, 6), "net_return": round(final / starting - 1.0, 6),
            "multiple": round(final / starting, 6), "max_drawdown": round(drawdown, 6),
            "trades": trades, "samples": samples}


def validate(dataset):
    bars = dataset["bars"]
    pairs = tuple(dataset.get("pairs") or ())
    if not pairs or len(set(pairs)) != len(pairs) or len(bars) < 440:
        raise ValueError("Valid pairs and at least 440 hourly bars required")
    if any(b["ts"] - a["ts"] != 3600 for a, b in zip(bars, bars[1:])):
        raise ValueError("Non-contiguous hourly data")
    for bar in bars:
        for pair in pairs:
            q = bar.get("prices", {}).get(pair, {})
            for field in ("open", "close"):
                price = q.get(field)
                if not isinstance(price, (float, int)) or not math.isfinite(price) or price <= 0:
                    raise ValueError("Missing or invalid genuine OHLC values")
    return bars, pairs


def evolve(dataset, *, generations=12, population=72, seed=6410):
    bars, pairs = validate(dataset)
    generations = max(1, min(int(generations), 30))
    population = max(8, min(int(population), 120))
    cut = int(len(bars) * 0.65)
    train, holdout = bars[:cut], bars[cut:]
    if len(train) < 320 or len(holdout) < WARMUP + 8:
        raise ValueError("Insufficient independent training and holdout hours")

    rng = random.Random(seed)
    # Idle cash is always an available rival, never a forced loss maker.
    cash_genome = normalize({name: values[0] for name, values in CHOICES.items()})
    genes = [cash_genome] + [random_genome(rng) for _ in range(population - 1)]
    cache = {}
    history = []

    def grade(g):
        k = key(g)
        if k not in cache:
            full = simulate(train, g, pairs)
            # Three training-only eras assess robustness. They overlap; none
            # is an independently reserved final validation set.
            lo = int(len(train) * 0.20)
            hi = int(len(train) * 0.80)
            eras = [train[:hi], train[lo:]]
            checks = [simulate(era, g, pairs) for era in eras]
            returns = [x["net_return"] for x in checks]
            utility = (
                0.5 * full["net_return"]
                + 0.5 * min(returns)
                - 0.65 * max(x["max_drawdown"] for x in checks)
                - 0.03 * max(0, len([x for x in checks if x["net_return"] < 0]))
            )
            cache[k] = (utility, full, returns)
        return cache[k]

    all_results = {}
    champion = None
    for generation in range(generations):
        ranked = sorted(((grade(g)[0], key(g), g) for g in genes),
                        key=lambda row: (-row[0], row[1]))
        for score, signature, g in ranked:
            all_results[signature] = g
        if champion is None or ranked[0][0] > champion[0]:
            champion = (ranked[0][0], ranked[0][2])
        history.append({
            "generation": generation + 1,
            "evaluated_unique": len(cache),
            "best_training_score": round(ranked[0][0], 8),
            "leader": ranked[0][2],
            "shortlist": [{"genome": g, "training_score": round(value, 8)}
                          for value, _, g in ranked[:5]],
            "training_result": grade(ranked[0][2])[1],
            "training_era_returns": grade(ranked[0][2])[2],
        })
        parents = [g for _, _, g in ranked[:max(4, population // 4)]]
        next_gen = [cash_genome] + [g for g in parents if key(g) != key(cash_genome)]
        while len(next_gen) < population:
            r = rng.random()
            if r < 0.20:
                next_gen.append(random_genome(rng))
            elif r < 0.70:
                next_gen.append(mutate(rng.choice(parents), rng))
            else:
                next_gen.append(mutate(crossover(*rng.sample(parents, 2), rng=rng), rng))
        genes = next_gen

    # Final holdout is opened ONCE after training selection. Do not use its
    # score to mutate, rerank, or select a different strategy.
    winner = champion[1]
    result = simulate(holdout, winner, pairs)
    cash = {"final": 25.0, "net_return": 0.0}
    # Benchmark buys BTC at the EXACT candidate start offset and includes
    # the same fee stress on entry and hypothetical exit. Other starting
    # points would bias the candidate-vs-BTC comparison.
    btc_pair = "BTC-USD" if "BTC-USD" in pairs else None
    if btc_pair:
        first = holdout[WARMUP]["prices"][btc_pair]["open"]
        last = holdout[-1]["prices"][btc_pair]["close"]
        btc_final = 25.0 * (1.0 - COST) ** 2 * last / first
        btc = {"final": round(btc_final, 6),
               "net_return": round(btc_final / 25.0 - 1.0, 6),
               "start_offset": WARMUP}
    else:
        raise ValueError("BTC-USD is required for like-for-like benchmark")
    passed = (result["final"] > max(cash["final"], btc["final"])
              and result["net_return"] > 0 and result["trades"] > 0)
    return {
        "schema": "bean.evolution.lab.v1",
        "dataset_source": dataset.get("source"),
        "train_bars": len(train), "holdout_bars": len(holdout),
        "pairs": list(pairs), "seed": seed, "generations": generations,
        "population": population, "candidates_tested": len(cache),
        "survivors": history, "champion": winner,
        "final_holdout": result, "cash": cash, "btc_holdout": btc,
        "historically_profitable": result["net_return"] > 0,
        "beats_both_benchmarks": passed,
        "release_ready": False,
        "model_authored": False,
        "notes": [
            "Evolutionary structured strategy search; no live wallet interaction.",
            "Selection uses training windows only; final holdout used once.",
            "Single chronology, not multi-regime forward validation.",
            "Search can overfit; apparent profits do not predict future returns.",
            "Broker minimum order size and fills are not verified by this simulation."
        ],
    }


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--dataset", type=Path, required=True)
    p.add_argument("--out", type=Path, default=Path("artifacts/bean-evolution.json"))
    p.add_argument("--generations", type=int, default=12)
    p.add_argument("--population", type=int, default=72)
    p.add_argument("--seed", type=int, default=6410)
    a = p.parse_args()
    report = evolve(json.loads(a.dataset.read_text(encoding="utf-8")),
                    generations=a.generations, population=a.population, seed=a.seed)
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({
        "candidates_tested": report["candidates_tested"],
        "generations": report["generations"],
        "champion": report["champion"],
        "holdout": report["final_holdout"],
        "btc_holdout": report["btc_holdout"],
        "historically_profitable": report["historically_profitable"],
        "beats_both_benchmarks": report["beats_both_benchmarks"],
    }, indent=2))


if __name__ == "__main__":
    main()
